// Writes the local-only env files from the committed *.env.example name lists:
//   infra/compose/.env   (database owner password for the dev Postgres container)
//   apps/api/.env        (API settings, generated local keys, local database URLs)
// Values are random per machine and never committed. Existing files are left alone unless --force.
// Provider keys (Paystack test keys, Resend, SMS, Telegram, PostHog, R2) are left empty: local
// transports are console-only, and real test keys come from the lead through SOPS.
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const force = process.argv.includes('--force');

const secret = () => randomBytes(32).toString('base64');
const password = () => randomBytes(24).toString('base64url');

function namesIn(examplePath: string): string[] {
  return readFileSync(examplePath, 'utf8')
    .split('\n')
    .map((line) => /^([A-Z0-9_]+)=/.exec(line)?.[1])
    .filter((name): name is string => name !== undefined);
}

function writeEnv(target: string, example: string, values: Record<string, string>) {
  if (existsSync(target) && !force) {
    process.stdout.write(`kept existing ${target.replace(root, '')} (use --force to regenerate)\n`);
    return false;
  }
  const names = namesIn(example);
  const unknown = Object.keys(values).filter((k) => !names.includes(k));
  if (unknown.length > 0) throw new Error(`not in ${example}: ${unknown.join(', ')}`);
  const body = names.map((n) => `${n}=${values[n] ?? ''}`).join('\n');
  writeFileSync(target, `# Local only. Generated by pnpm local:env. Do not commit.\n${body}\n`, {
    mode: 0o600,
  });
  const empty = names.filter((n) => (values[n] ?? '') === '');
  process.stdout.write(`wrote ${target.replace(root, '')}`);
  process.stdout.write(empty.length > 0 ? ` (left empty: ${empty.join(', ')})\n` : '\n');
  return true;
}

const composeEnvPath = `${root}infra/compose/.env`;
const ownerPassword = existsSync(composeEnvPath)
  ? (/^SKIPA_OWNER_DB_PASSWORD=(.+)$/m.exec(readFileSync(composeEnvPath, 'utf8'))?.[1] ??
    password())
  : password();
writeEnv(composeEnvPath, `${root}infra/compose/.env.example`, {
  SKIPA_OWNER_DB_PASSWORD: ownerPassword,
  SKIPA_DB_PORT: '5432',
});

const exitKey = generateKeyPairSync('ed25519').privateKey.export({ type: 'pkcs8', format: 'pem' });
const db = (user: string, pw: string) => `postgres://${user}:${pw}@127.0.0.1:5432/skipa`;

